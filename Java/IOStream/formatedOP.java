
public class formatedOP {
    public static void main(String[] args) {
        int n = 90;
        System.out.printf("this is decimal n %d", n);
        float f = 4;
        System.out.println();
        System.out.printf("this is float f %8.3f", f);
        System.out.println();
        System.out.printf("this is float f %8.3f%n", f);
        System.out.printf("ending");

    }
}
